/**
 * Build a subset of Font Awesome 7 Free "solid" (fa-solid-900) containing only
 * the glyphs Xylonic actually references, and emit it + its @font-face CSS.
 *
 *   node scripts/build-fa-subset.mjs        (also: npm run fa:subset)
 *
 * Why: the full fa-solid-900.woff2 is ~115 kB for ~1400 glyphs; the app uses
 * under 130. The scan covers static `fa-xxx` class tokens, dynamic
 * `fa-${cond ? 'a' : 'b'}` ternaries (string literals inside the braces), and
 * `icon: 'fa-xxx'` config values. Anything the scan can't see goes in EXTRA.
 *
 * Output (committed to the repo, not part of `npm run build`):
 *   src/assets/fonts/fa-solid-subset.woff2
 *   src/styles/fa-solid-subset.css
 */

import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from 'node:fs';
import { join, extname, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'src');
const FA = join(ROOT, 'node_modules/@fortawesome/fontawesome-free');

const meta = require('@fortawesome/fontawesome-free/metadata/icon-families.json');

// Icons referenced dynamically in ways the scanner can't resolve. Keep empty
// unless on-device QA turns up a missing glyph; add the bare name here.
const EXTRA = [];

// `fa-*` tokens that are style/sizing/animation utilities, never glyph names.
const UTIL = new Set([
  'solid', 'regular', 'brands', 'classic', 'sharp', 'duotone', 'thin', 'light',
  'spin', 'spin-pulse', 'spin-reverse', 'pulse', 'fw', 'border', 'inverse',
  'pull-left', 'pull-right', 'beat', 'fade', 'beat-fade', 'bounce', 'shake', 'flip',
  'flip-horizontal', 'flip-vertical', 'flip-both', 'rotate-90', 'rotate-180',
  'rotate-270', 'rotate-by', 'stack', 'stack-1x', 'stack-2x', 'layers',
  'layers-text', 'layers-counter', 'xs', 'sm', 'lg', 'xl', '2xs', '2xl',
  '1x', '2x', '3x', '4x', '5x', '6x', '7x', '8x', '9x', '10x',
]);

// name -> free "classic solid" unicode codepoint (hex string)
const solidUnicode = new Map();
for (const [name, entry] of Object.entries(meta)) {
  const free = entry.familyStylesByLicense?.free ?? [];
  if (!free.some(f => f.family === 'classic' && f.style === 'solid')) continue;
  solidUnicode.set(name, entry.unicode);
  for (const alias of entry.aliases?.names ?? []) solidUnicode.set(alias, entry.unicode);
}

const GENERATED = join(SRC, 'styles/fa-solid-subset.css');

function walk(dir) {
  const out = [];
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else if (p !== GENERATED && ['.ts', '.tsx', '.js', '.jsx', '.css', '.html'].includes(extname(p))) out.push(p);
  }
  return out;
}

const found = new Set(EXTRA);
const seenRaw = new Set();

for (const file of walk(SRC)) {
  const text = readFileSync(file, 'utf8');

  // Static `fa-xxx` tokens (class strings, `icon: 'fa-xxx'`, CSS, etc.)
  for (const m of text.matchAll(/fa-([a-z0-9]+(?:-[a-z0-9]+)*)/g)) {
    seenRaw.add(m[1]);
    if (!UTIL.has(m[1])) found.add(m[1]);
  }

  // Dynamic `fa-[stem-]${ ...expr... }` — combine an optional static stem
  // (e.g. `fa-chevron-${dir}`) with the string literals inside the braces.
  for (const m of text.matchAll(/fa-([a-z0-9-]*?)\$\{([^}]*)\}/g)) {
    const stem = m[1]; // '' or e.g. 'chevron-' / 'sync-alt'
    if (stem) {
      const base = stem.replace(/-$/, '');
      if (!UTIL.has(base)) { seenRaw.add(base); found.add(base); }
    }
    for (const lit of m[2].matchAll(/['"`]([^'"`]+)['"`]/g)) {
      for (const part of lit[1].trim().split(/\s+/)) {
        // A `fa-`-prefixed literal is its own class, not a suffix of the stem.
        const name = part.startsWith('fa-') ? part.slice(3) : stem + part;
        if (name && !UTIL.has(name)) { seenRaw.add(name); found.add(name); }
      }
    }
  }
}

const resolved = new Map(); // name -> codepoint
const missing = [];
for (const name of [...found].sort()) {
  const cp = solidUnicode.get(name);
  if (cp) resolved.set(name, cp);
  else missing.push(name);
}

const codepoints = [...new Set(resolved.values())].map(h => parseInt(h, 16));
const glyphText = codepoints.map(c => String.fromCodePoint(c)).join('');

const srcFont = readFileSync(join(FA, 'webfonts/fa-solid-900.woff2'));
const subset = await subsetFont(srcFont, glyphText, { targetFormat: 'woff2' });

const outFontDir = join(SRC, 'assets/fonts');
mkdirSync(outFontDir, { recursive: true });
writeFileSync(join(outFontDir, 'fa-solid-subset.woff2'), subset);

const css = `/* Generated by scripts/build-fa-subset.mjs — do not edit by hand.
 * Subset of Font Awesome 7 Free "solid" (${resolved.size} glyphs) replacing the
 * full fa-solid-900 webfont. Pair with fontawesome.min.css (icon codepoint vars
 * + utilities). Regenerate with: npm run fa:subset
 */
:root {
  --fa-family-classic: "Font Awesome 7 Free";
  --fa-font-solid: normal 900 1em/1 var(--fa-family-classic);
  --fa-style-family-classic: var(--fa-family-classic);
}
@font-face {
  font-family: "Font Awesome 7 Free";
  font-style: normal;
  font-weight: 900;
  font-display: block;
  src: url("../assets/fonts/fa-solid-subset.woff2") format("woff2");
}
.fas { --fa-style: 900; }
.fa-classic, .fas { --fa-family: var(--fa-family-classic); }
.fa-solid { --fa-style: 900; }
`;
mkdirSync(join(SRC, 'styles'), { recursive: true });
writeFileSync(join(SRC, 'styles/fa-solid-subset.css'), css);

console.log(`fa subset: ${resolved.size} glyphs, ${(subset.length / 1024).toFixed(1)} kB woff2 (was ${(srcFont.length / 1024).toFixed(1)} kB)`);
if (missing.length) {
  console.log(`\nUnresolved fa- tokens (not free solid icons — check if any are real & add to EXTRA):`);
  console.log('  ' + missing.join(', '));
}
